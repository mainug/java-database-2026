-- DML - UPDATE

-- DEPT_TEMP2 생성
CREATE TABLE DEPT_TEMP2
AS SELECT * FROM DEPT;

-- 확인 조회
SELECT * FROM DEPT_TEMP2;

-- 전체데이터 수정! (조심)
UPDATE DEPT_TEMP2
SET LOC = 'SEOUL';

-- DELETE FROM DEPT_TEMP2;

INSERT INTO DEPT_TEMP2 (DEPTNO, DNAME, LOC)
SELECT DEPTNO, DNAME, LOC
FROM DEPT;

-- 일반적인 UPDATE
UPDATE DEPT_TEMP2
SET LOC = 'BUSAN'
WHERE DEPTNO = 40;

-- 서브쿼리로 업데이트
UPDATE DEPT_TEMP2
SET LOC = 'LOS ANGELES'
WHERE DEPTNO = (SELECT DEPTNO
				FROM DEPT_TEMP2
				WHERE DNAME = 'OPERATIONS');

